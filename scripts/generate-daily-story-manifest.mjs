import { readdir, readFile, stat, writeFile, mkdir } from 'node:fs/promises'
import { join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const projectRoot = resolve(fileURLToPath(new URL('..', import.meta.url)))
const dailyStoriesDirectory = join(projectRoot, 'public', 'daily-stories')
const generatedManifestPath = join(projectRoot, 'src', 'data', 'generated', 'dailyStoryManifest.ts')
const validVibes = new Set([
  'guilty',
  'hungry',
  'judging',
  'dramatic',
  'sleepy',
  'excited',
  'suspicious',
  'chaos',
])

function isValidDateDirectory(name) {
  const match = /^(\d{4})-(\d{2})-(\d{2})$/.exec(name)
  if (!match) return false

  const [, year, month, day] = match
  const timestamp = Date.UTC(Number(year), Number(month) - 1, Number(day))
  const date = new Date(timestamp)

  return date.getUTCFullYear() === Number(year)
    && date.getUTCMonth() === Number(month) - 1
    && date.getUTCDate() === Number(day)
}

async function isFile(path) {
  try {
    return (await stat(path)).isFile()
  } catch {
    return false
  }
}

async function readStoryDirectory(date) {
  const storyDirectory = join(dailyStoriesDirectory, date)

  try {
    const storyJson = JSON.parse(await readFile(join(storyDirectory, 'story.json'), 'utf8'))
    const storyKeys = Object.keys(storyJson).sort()
    const expectedKeys = ['alt', 'title', 'vibe']

    if (!storyJson || typeof storyJson !== 'object' || Array.isArray(storyJson)) {
      throw new Error('story.json must contain a JSON object')
    }
    if (storyKeys.some((key, index) => key !== expectedKeys[index])) {
      throw new Error('story.json must contain only title, vibe, and alt metadata')
    }
    if (typeof storyJson.title !== 'string' || storyJson.title.trim() === '') {
      throw new Error('story.json title must be a non-empty string')
    }
    if (typeof storyJson.alt !== 'string' || storyJson.alt.trim() === '') {
      throw new Error('story.json alt must be a non-empty string')
    }
    if (typeof storyJson.vibe !== 'string' || !validVibes.has(storyJson.vibe)) {
      throw new Error(`story.json vibe must be one of: ${[...validVibes].join(', ')}`)
    }
    if (!(await isFile(join(storyDirectory, 'cover.jpg')))) {
      throw new Error('cover.jpg is missing')
    }

    const files = await readdir(storyDirectory, { withFileTypes: true })
    const slides = files
      .filter((entry) => entry.isFile() && /^(\d{2})\.jpg$/.test(entry.name))
      .map((entry) => ({ name: entry.name, number: Number(entry.name.slice(0, 2)) }))
      .filter((slide) => slide.number > 0)
      .sort((left, right) => left.number - right.number)

    if (slides.length === 0) {
      throw new Error('at least one numbered slide (01.jpg, 02.jpg, ...) is required')
    }
    slides.forEach((slide, index) => {
      if (slide.number !== index + 1) {
        throw new Error('numbered slides must be consecutive starting at 01.jpg')
      }
    })

    return {
      date,
      title: storyJson.title.trim(),
      vibe: storyJson.vibe,
      alt: storyJson.alt.trim(),
      cover: `/daily-stories/${date}/cover.jpg`,
      slides: slides.map((slide) => `/daily-stories/${date}/${slide.name}`),
    }
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error)
    console.warn(`[daily-stories] Skipping ${date}: ${message}`)
    return null
  }
}

async function generateManifest() {
  let entries = []

  try {
    const directories = await readdir(dailyStoriesDirectory, { withFileTypes: true })
    const dates = directories
      .filter((entry) => entry.isDirectory() && isValidDateDirectory(entry.name))
      .map((entry) => entry.name)
      .sort()
    entries = (await Promise.all(dates.map(readStoryDirectory))).filter(Boolean)
  } catch (error) {
    if (error?.code !== 'ENOENT') throw error
  }

  const source = `// Generated by scripts/generate-daily-story-manifest.mjs. Do not edit by hand.\n\nexport const dailyStoryManifest = ${JSON.stringify(entries, null, 2)} as const\n`
  await mkdir(resolve(generatedManifestPath, '..'), { recursive: true })
  await writeFile(generatedManifestPath, source)
  console.log(`[daily-stories] Generated ${entries.length} ${entries.length === 1 ? 'story' : 'stories'} at ${generatedManifestPath}`)
}

await generateManifest()
